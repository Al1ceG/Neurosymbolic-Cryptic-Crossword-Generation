def run_pipeline(words: list[str], size: int, min_quality: int = 0):
    """
    Run encode → solve → interpret for the given parameters, mirroring the
    pre-processing that generate_crossword applies.

    Returns (placements, size) where placements is a list of
    (word, x, y, orientation) tuples, or (None, size) if the instance is UNSAT.
    """
    words = list(dict.fromkeys(w.upper() for w in words))
    constraints, placement_vars = encode_problem(words, size, min_quality)
    model = solve(constraints)
    if model is None:
        return None, size
    return interpret(model, placement_vars, size), size


def build_grid(placements: list[tuple], size: int) -> list[list]:
    """
    Reconstruct the character grid from a list of (word, x, y, orientation)
    tuples.  Returns a size×size list-of-lists; None means an empty cell.
    """
    grid = [[None] * size for _ in range(size)]
    for word, x, y, orientation in placements:
        for k, ch in enumerate(word):
            if orientation == "horizontal":
                grid[y][x + k] = ch
            else:
                grid[y + k][x] = ch
    return grid


def is_connected(grid: list[list], size: int) -> bool:
    """Return True iff all non-empty cells form a single connected component."""
    cells = [(r, c) for r in range(size) for c in range(size) if grid[r][c] is not None]
    if not cells:
        return True
    visited = {cells[0]}
    queue = [cells[0]]
    while queue:
        r, c = queue.pop()
        for dr, dc in [(-1, 0), (1, 0), (0, -1), (0, 1)]:
            nr, nc = r + dr, c + dc
            if (
                0 <= nr < size
                and 0 <= nc < size
                and grid[nr][nc] is not None
                and (nr, nc) not in visited
            ):
                visited.add((nr, nc))
                queue.append((nr, nc))
    return len(visited) == len(cells)


