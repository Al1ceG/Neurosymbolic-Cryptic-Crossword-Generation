class TestEncodeProblem:
    """Verify the constraint-list structure returned by encode_problem."""

    def test_returns_nonempty_constraint_list(self):
        """At least one constraint must be generated."""
        constraints, _ = encode_problem(["CAT", "DOG"], 5, 0)
        assert isinstance(constraints, list)
        assert len(constraints) > 0

    def test_placement_vars_keys_match_words(self):
        """The returned placement_vars must have exactly the supplied word keys."""
        words = ["CAT", "DOG", "COT"]
        _, placement_vars = encode_problem(words, 5, 0)
        assert set(placement_vars.keys()) == set(words)

    def test_more_words_produces_more_constraints(self):
        """Adding more words must strictly increase the constraint count."""
        c_small, _ = encode_problem(["CAT"], 5, 0)
        c_large, _ = encode_problem(["CAT", "DOG", "COT", "OAT"], 5, 0)
        assert len(c_large) > len(c_small)

    def test_positive_min_quality_adds_extra_constraint(self):
        """Setting min_quality > 0 must add at least one constraint beyond the baseline."""
        c_no_q, _ = encode_problem(["CAT", "DOG"], 5, 0)
        c_with_q, _ = encode_problem(["CAT", "DOG"], 5, 3)
        assert len(c_with_q) > len(c_no_q)

    def test_zero_min_quality_adds_no_quality_constraint(self):
        """min_quality == 0 must produce the same constraint count as a second call with 0."""
        c1, _ = encode_problem(["CAT", "DOG"], 5, 0)
        c2, _ = encode_problem(["CAT", "DOG"], 5, 0)
        assert len(c1) == len(c2)


