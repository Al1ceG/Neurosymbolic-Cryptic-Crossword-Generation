class TestPrintPlacement:
    """Verify the ASCII-grid rendering produced by print_placement."""

    def _data_rows(self, output: str) -> list[str]:
        """Extract the content rows (lines that contain '|' but not '+')."""
        return [l for l in output.splitlines() if "|" in l and "+" not in l]

    def test_empty_grid_shows_all_dots(self):
        """With no placements, every cell must render as '.'."""
        f = io.StringIO()
        with redirect_stdout(f):
            print_placement([], 3)
        for row in self._data_rows(f.getvalue()):
            inner = row.split("|")[1]
            assert set(inner) == {"."}, f"Expected all dots, got: {inner!r}"

    def test_output_has_exactly_size_data_rows(self):
        """print_placement must output exactly `size` data rows."""
        size = 4
        f = io.StringIO()
        with redirect_stdout(f):
            print_placement([], size)
        assert len(self._data_rows(f.getvalue())) == size

    def test_horizontal_word_appears_in_correct_row(self):
        """A word placed horizontally at row y must appear on the y-th data line."""
        # Place "CAT" horizontally starting at (0, 1) — so it should appear on row 1.
        f = io.StringIO()
        with redirect_stdout(f):
            print_placement([("CAT", 0, 1, "horizontal")], 5)
        rows = self._data_rows(f.getvalue())
        assert "CAT" in rows[1], "CAT should appear on data row 1"
        # Row 0 should still be all dots
        assert set(rows[0].split("|")[1]) == {"."}, "Row 0 should be empty"

    def test_vertical_word_appears_in_correct_column(self):
        """A word placed vertically at column x must set the correct cell in each row."""
        # Place "DOG" vertically at (col=2, row=0) — rows 0,1,2 should have D,O,G at col 2.
        f = io.StringIO()
        with redirect_stdout(f):
            print_placement([("DOG", 2, 0, "vertical")], 5)
        rows = self._data_rows(f.getvalue())
        for i, ch in enumerate("DOG"):
            inner = rows[i].split("|")[1]
            assert inner[2] == ch, f"Expected '{ch}' at col 2 of row {i}, got '{inner[2]}'"


