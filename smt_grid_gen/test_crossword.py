class TestIntegration:
    """
    Verify crossword correctness independently of Z3 by re-examining the
    returned placements with plain Python logic.
    """

    def test_instance_is_satisfiable(self, four_word_solution):
        """The known-solvable word set must produce at least one placement."""
        placements, _ = four_word_solution
        assert len(placements) >= 1

    def test_placed_words_come_from_input_list(self, four_word_solution):
        """Every word in the output must appear in the original input list."""
        placements, _ = four_word_solution
        valid_words = {"CAT", "DOG", "COT", "OAT"}
        for word, *_ in placements:
            assert word in valid_words, f"'{word}' was not in the input word list"

    def test_word_characters_match_grid_cells(self, four_word_solution):
        """
        Reconstruct the grid from placements and confirm that each placed word's
        letters are consistent with the cell values it occupies (Rule 1).
        """
        placements, size = four_word_solution
        grid = build_grid(placements, size)
        for word, x, y, orientation in placements:
            for k, ch in enumerate(word):
                if orientation == "horizontal":
                    assert grid[y][x + k] == ch, (
                        f"{word} h@({x},{y}): expected '{ch}' at col {x+k} row {y}"
                    )
                else:
                    assert grid[y + k][x] == ch, (
                        f"{word} v@({x},{y}): expected '{ch}' at row {y+k} col {x}"
                    )

    def test_no_cell_holds_conflicting_characters(self, four_word_solution):
        """
        A cell shared by two crossing words must carry the same letter in both
        (Rule 1 bi-directional check).
        """
        placements, size = four_word_solution
        seen: dict[tuple, str] = {}
        for word, x, y, orientation in placements:
            for k, ch in enumerate(word):
                pos = (y + k, x) if orientation == "vertical" else (y, x + k)
                if pos in seen:
                    assert seen[pos] == ch, (
                        f"Character conflict at {pos}: '{seen[pos]}' vs '{ch}'"
                    )
                else:
                    seen[pos] = ch

    def test_boundary_cells_are_empty(self, four_word_solution):
        """
        The cell immediately before the start and after the end of each placed
        word (in its own direction) must be empty (Rule 2).
        """
        placements, size = four_word_solution
        grid = build_grid(placements, size)
        for word, x, y, orientation in placements:
            if orientation == "horizontal":
                if x - 1 >= 0:
                    assert grid[y][x - 1] is None, (
                        f"Cell before '{word}' h@({x},{y}) should be empty"
                    )
                if x + len(word) < size:
                    assert grid[y][x + len(word)] is None, (
                        f"Cell after '{word}' h@({x},{y}) should be empty"
                    )
            else:
                if y - 1 >= 0:
                    assert grid[y - 1][x] is None, (
                        f"Cell above '{word}' v@({x},{y}) should be empty"
                    )
                if y + len(word) < size:
                    assert grid[y + len(word)][x] is None, (
                        f"Cell below '{word}' v@({x},{y}) should be empty"
                    )

    def test_all_placed_cells_form_a_connected_component(self, four_word_solution):
        """
        All non-empty cells must form a single connected component (Rule 5).
        This is verified independently using BFS.
        """
        placements, size = four_word_solution
        grid = build_grid(placements, size)
        assert is_connected(grid, size), (
            "Placed words do not form a single connected component"
        )

    # -- Specific scenario tests (each calls run_pipeline independently) -----------

    def test_single_word_produces_exactly_one_placement(self):
        """
        A word list containing only one word must result in exactly that one word
        being placed.  min_quality=1 forces it to be selected.
        """
        # HELLO has length 5, filling an entire row or column on a 5×5 grid.
        placements, _ = run_pipeline(["HELLO"], 5, min_quality=1)
        assert placements is not None
        assert len(placements) == 1
        assert placements[0][0] == "HELLO"

    def test_lowercase_words_are_treated_as_uppercase(self):
        """
        Words provided in lowercase must be uppercased; the output should contain
        only uppercase characters.
        """
        placements, _ = run_pipeline(["cat", "dog", "cot", "oat"], 5)
        assert placements is not None
        for word, *_ in placements:
            assert word == word.upper(), f"Expected uppercase, got '{word}'"

    def test_duplicate_words_are_deduplicated(self):
        """
        Supplying the same word multiple times must not cause it to be placed more
        than once (the encoding deduplicates before encoding).
        """
        placements, _ = run_pipeline(["CAT", "CAT", "DOG"], 5)
        assert placements is not None
        placed = [w for w, *_ in placements]
        assert placed.count("CAT") <= 1, "CAT must appear at most once"

    def test_min_quality_constraint_is_satisfied(self):
        """
        When min_quality is set, the number of placed words must be at least
        that value.
        """
        min_q = 2
        placements, _ = run_pipeline(["CAT", "DOG", "COT", "OAT"], 5, min_quality=min_q)
        assert placements is not None, f"Expected SAT with min_quality={min_q}"
        quality = len(placements)
        assert quality >= min_q, f"Quality {quality} is below min_quality {min_q}"

    def test_unsatisfiable_quality_returns_none(self):
        """
        A min_quality that exceeds the total length of all words combined is
        impossible; the solver must return None (UNSAT).
        """
        # "CAT" has length 3; requiring quality ≥ 100 is impossible.
        placements, _ = run_pipeline(["CAT"], 5, min_quality=100)
        assert placements is None, "Expected UNSAT for impossible quality constraint"

    def test_incompatible_words_forced_together_returns_none(self):
        """
        Two words that share no letters cannot form a connected crossword on a 2×2
        grid when both are forced to be placed (via min_quality).  The solver must
        return None (UNSAT).

        AA and BB each need 2 cells; on a 2×2 grid any layout that connects them
        would require a cell to simultaneously hold 'A' and 'B', which is a
        contradiction.  The quality threshold (4) forces both words to be selected.
        """
        placements, _ = run_pipeline(["AA", "BB"], 2, min_quality=4)
        assert placements is None, "Expected UNSAT for AA+BB on 2×2 with min_quality=4"
